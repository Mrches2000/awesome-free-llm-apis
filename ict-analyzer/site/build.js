#!/usr/bin/env node
'use strict';
// Bundles the analysis modules into one browser script (site/engine.js) for the
// private site. The same code runs in the local app and on the site.
const fs = require('node:fs');
const path = require('node:path');

const MODULES = ['time', 'candles', 'ict', 'instruments', 'narrative', 'analyze', 'vision'];
const lib = path.join(__dirname, '..', 'lib');
const parts = MODULES.map((name) => `  ${JSON.stringify(name)}: function (module, exports, require) {\n${fs.readFileSync(path.join(lib, `${name}.js`), 'utf8')}\n  }`);
const out = `/* Generated by site/build.js from lib/*.js — do not edit by hand. */
(function () {
var defs = {
${parts.join(',\n')}
};
var cache = {};
function load(name) {
  name = String(name).replace(/^\\.\\//, '').replace(/\\.js$/, '');
  if (cache[name]) return cache[name].exports;
  if (!defs[name]) throw new Error('Module not bundled: ' + name);
  var m = { exports: {} };
  cache[name] = m;
  defs[name](m, m.exports, load);
  return m.exports;
}
window.ICT = { vision: load('vision'), analyze: load('analyze'), time: load('time'), instruments: load('instruments') };
}());
`;
fs.writeFileSync(path.join(__dirname, 'engine.js'), out);
console.log(`site/engine.js written (${(out.length / 1024).toFixed(0)} KB)`);
