#!/usr/bin/env node
'use strict';
// Bundles the analysis modules into one browser script (site/engine.js) for the
// private site. The same code runs in the local app and on the site.
const fs = require('node:fs');
const path = require('node:path');

const MODULES = ['time', 'candles', 'ict', 'instruments', 'narrative', 'analyze', 'vision', 'data'];
const lib = path.join(__dirname, '..', 'lib');
const parts = MODULES.map((name) => `  ${JSON.stringify(name)}: function (module, exports, require) {\n${fs.readFileSync(path.join(lib, `${name}.js`), 'utf8')}\n  }`);
const out = `/* Generated by site/build.js from lib/*.js — do not edit by hand. */
(function () {
var process = { env: {} }; // the browser has no process; the modules only read settings from it
var defs = {
${parts.join(',\n')}
};
var cache = {};
function load(name) {
  name = String(name).replace(/^\\.\\//, '').replace(/\\.js$/, '');
  if (cache[name]) return cache[name].exports;
  if (!defs[name]) throw new Error('Module not bundled: ' + name);
  var m = { exports: {} };
  cache[name] = m;
  defs[name](m, m.exports, load);
  return m.exports;
}
window.ICT = { vision: load('vision'), analyze: load('analyze'), time: load('time'), instruments: load('instruments'), data: load('data') };
}());
`;
fs.writeFileSync(path.join(__dirname, 'engine.js'), out);
console.log(`site/engine.js written (${(out.length / 1024).toFixed(0)} KB)`);

// Every source file, bundled as data so the private site can show and copy the full code.
const root = path.join(__dirname, '..');
const skip = new Set(['site/engine.js', 'site/source.json']);
const listed = [];
(function walk(dir) {
  for (const name of fs.readdirSync(dir).sort()) {
    if (name === 'node_modules' || name.startsWith('.git')) continue;
    const full = path.join(dir, name);
    if (fs.statSync(full).isDirectory()) walk(full);
    else {
      const rel = path.relative(root, full).split(path.sep).join('/');
      if (!skip.has(rel) && /\.(js|json|html|css|md)$/.test(rel)) listed.push(rel);
    }
  }
}(root));
const files = {};
for (const rel of listed) files[rel] = fs.readFileSync(path.join(root, rel), 'utf8');
fs.writeFileSync(path.join(__dirname, 'source.json'), JSON.stringify({
  project: 'ict-analyzer',
  note: 'Full source of the ICT Analyzer. site/engine.js is generated: run "node site/build.js" to recreate it.',
  files,
}));
console.log(`site/source.json written (${listed.length} files, ${(JSON.stringify(files).length / 1024).toFixed(0)} KB)`);
